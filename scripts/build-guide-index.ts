/**
 * Generate src/data/guides/index.ts from the guide JSON files that pass validation.
 * Runs automatically before `dev` and `build`; invalid guides are skipped with a warning.
 */
import fs from "node:fs";
import path from "node:path";
import { GuideSchema, crossCheckGuide } from "../src/lib/guide/schema";

const dir = path.join(process.cwd(), "src", "data", "guides");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const ok: string[] = [];
for (const f of files) {
  try {
    const parsed = GuideSchema.safeParse(JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")));
    if (!parsed.success || crossCheckGuide(parsed.data).length) {
      console.warn(`guide index: skipping ${f} (run npm run validate -- ${f.replace(/\.json$/, "")})`);
      continue;
    }
    ok.push(f.replace(/\.json$/, ""));
  } catch (e) {
    console.warn(`guide index: skipping ${f}: ${(e as Error).message}`);
  }
}
const ident = (s: string) => `g_${s.replace(/[^a-z0-9]/g, "_")}`;
const body = [
  "// Generated by scripts/build-guide-index.ts. Do not edit by hand.",
  ...ok.map((s) => `import ${ident(s)} from "./${s}.json";`),
  "",
  `export const CURATED_RAW: unknown[] = [${ok.map(ident).join(", ")}];`,
  "",
].join("\n");
fs.writeFileSync(path.join(dir, "index.ts"), body);
console.log(`guide index: ${ok.length} curated guide(s): ${ok.join(", ") || "none"}`);
