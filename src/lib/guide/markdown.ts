import { CORE_QUESTIONS, GATE_LEVELS, type Evidence, type EvidenceLabel, type Owner } from "./schema";
import { ACCESS_LABEL, AUDIENCE_LABEL } from "./intake";
import { LEVEL_MEANING, LEVEL_NAMES, formatGateWait, stepMinutes, strongestLabel } from "./scoring";
import { VERDICT_SHORT } from "./verdict";
import type { GuideView } from "./view";

export const OWNER_LABEL: Record<Owner, string> = {
  agent_done: "Done by agent",
  agent_can_do: "Agent can do",
  agent_drafts: "Agent drafts, you submit",
  you: "You",
};

export const LABEL_TEXT: Record<EvidenceLabel, string> = {
  tested: "Tested",
  official: "Official",
  reported: "Reported",
  unverified: "Unverified",
};

export const LEGEND = {
  levels: ([1, 2, 3, 4] as const).map((l) => ({ level: l, name: LEVEL_NAMES[l], meaning: LEVEL_MEANING[l] })),
  labels: [
    { label: "Tested", meaning: "We or the agent did it and saw the result, on the date shown." },
    { label: "Official", meaning: "Stated in the provider's own documentation, linked and dated." },
    { label: "Reported", meaning: "Community or third-party source; may be dated or anecdotal." },
    { label: "Unverified", meaning: "Inferred, or no source found. Treat as a question to check." },
  ],
  owners: [
    { owner: "Done by agent", meaning: "Already checked during research; result and date shown." },
    { owner: "Agent can do", meaning: "The page can run this check for you now." },
    { owner: "Agent drafts, you submit", meaning: "Copy-ready text or values; you paste and submit." },
    { owner: "You", meaning: "Needs your login, money, legal identity, a video, or the final Submit." },
  ],
};

function cite(ids: string[], view: GuideView): string {
  if (!ids.length) return "";
  const labels = ids.map((id) => view.evidence.get(id)).filter((e): e is Evidence => !!e);
  if (!labels.length) return "";
  const nums = ids
    .map((id) => view.evidenceList.findIndex((e) => e.id === id) + 1)
    .filter((n) => n > 0)
    .map((n) => `[${n}]`)
    .join("");
  return ` _(${LABEL_TEXT[strongestLabel(ids, view.evidence)]} ${nums})_`;
}

export function guideToMarkdown(view: GuideView, url?: string): string {
  const { guide, path, level, wait, effort, confidence, verdict, intake } = view;
  const L: string[] = [];
  const push = (...xs: string[]) => L.push(...xs);
  push(`# OAuth readiness: ${guide.app.name}`, "");
  push(
    `> ${guide.headline}`,
    "",
    `For: **${AUDIENCE_LABEL[intake.audience]}** · **${ACCESS_LABEL[intake.access]}** · ${intake.brand ? "**your brand on the consent screen**" : "**Composio branding is fine**"}  `,
    `Path: **${path.label}** · Last verified ${guide.last_verified} · ${guide.kind === "curated" ? "Curated guide" : "Generated by agent"}${url ? `  \nLink: ${url}` : ""}`,
    "",
  );
  push(`## Verdict: ${VERDICT_SHORT[verdict.type]}`, "", verdict.summary, "");
  for (const r of verdict.reasons) push(`- ${r.text}${cite(r.evidence ?? [], view)}`);
  push("", "## At a glance", "");
  push(
    `| Difficulty | Hands-on effort | Calendar wait | Confidence |`,
    `|---|---|---|---|`,
    `| Level ${level.value}${level.unconfirmed ? "+ (unconfirmed)" : ""}: ${level.name} | ${effort.label} (our estimate) | ${wait.label}${wait.basis ? ` (${LABEL_TEXT[wait.basis]})` : ""} | ${confidence.value[0].toUpperCase()}${confidence.value.slice(1)} |`,
    "",
  );
  if (path.badges.length) {
    push("**Watch for:**", "");
    for (const b of path.badges) push(`- ${b.kind.replace("_", " ")}: ${b.text}${cite(b.evidence, view)}`);
    push("");
  }
  push("## Start here", "");
  path.start_here.forEach((s) => push(`1. **${s.when}:** ${s.action} — _${OWNER_LABEL[s.owner]}_`));
  push("");
  if (path.gates.length) {
    push("## Gates on this path", "");
    for (const g of path.gates) {
      const w = formatGateWait(g.wait);
      push(`### ${g.title} (Level ${GATE_LEVELS[g.type]})`, "", `- Triggered by: ${g.trigger}`, `- Wait: ${w}${g.wait?.note ? ` (${g.wait.note})` : ""}${cite(g.evidence, view)}`);
      if (g.avoid) push(`- How to avoid: ${g.avoid}`);
      if (g.after) push(`- Starts after: ${path.gates.find((x) => x.id === g.after)?.title ?? g.after}`);
      if (g.recurring) push(`- Repeats: ${g.recurring}`);
      push("");
    }
  } else push("## Gates on this path", "", "None: no review or verification is required on this path.", "");
  if (view.scopeAdvice.pathScopes.length) {
    push("## Scopes for this path", "");
    for (const s of view.scopeAdvice.pathScopes) push(`- \`${s.scope}\`: ${s.tier.replace("_", " ")}${s.what ? `. ${s.what}` : ""}`);
    if (view.scopeAdvice.warning) push("", `> ${view.scopeAdvice.warning}`);
    push("");
  }
  if (view.prerequisites.length) {
    push("## Before you start", "");
    for (const p of view.prerequisites) push(`- [ ] ${p.item}: ${p.why} — _${OWNER_LABEL[p.owner]}_${cite(p.evidence, view)}`);
    push("");
  }
  push("## Steps", "");
  view.steps.forEach((s, i) => {
    push(`${i + 1}. [ ] **${s.title}** — _${OWNER_LABEL[s.owner]}, ~${stepMinutes(s)} min_${cite(s.evidence, view)}  `, `   ${s.detail}`);
    for (const p of s.paste ?? []) push(`   - ${p.label}: \`${p.value.replace(/\n/g, " ")}\``);
    if (s.link) push(`   - ${s.link.label}: ${s.link.url}`);
  });
  push("");
  if (view.whileYouWait.length) {
    push("## While you wait", "");
    for (const w of view.whileYouWait) push(`- ${w.text}`);
    push("");
  }
  if (view.blockers.length) {
    push("## If you get blocked", "");
    for (const b of view.blockers) {
      push(`### ${b.symptom}`, "", `- Likely cause: ${b.cause}`, `- Fix now: ${b.fix_now}`, `- Fix properly: ${b.fix_properly}`, `- Escalate: ${b.escalate.how}${b.escalate.url ? ` (${b.escalate.url})` : ""}`);
      if (b.escalate.draft) push("", "  Draft message:", "", ...b.escalate.draft.split("\n").map((l) => `  > ${l}`));
      push("");
    }
  }
  push("## Connect it to Composio", "");
  view.wiring.forEach((w, i) => {
    push(`${i + 1}. **${w.title}** — _${OWNER_LABEL[w.owner]}_  `, `   ${w.detail}`);
    for (const p of w.paste ?? []) push("", "   ```", ...p.value.split("\n").map((l) => `   ${l}`), "   ```");
  });
  for (const n of guide.composio_notes) push(`- Note: ${n.text}${cite(n.evidence, view)}`);
  push("");
  push("## What we checked", "");
  for (const q of CORE_QUESTIONS) {
    const c = guide.checks.find((x) => x.q === q.id);
    push(`- ${q.text} **${c ? c.answer : "not checked"}**${c?.detail ? `: ${c.detail}` : ""}${c ? cite(c.evidence, view) : ""}`);
  }
  push("");
  if (view.unknowns.length) {
    push("## Still uncertain", "");
    for (const u of view.unknowns) push(`- ${u.question} ${u.why} How to find out: ${u.how_to_find_out}${u.level_deciding ? " (could change the level)" : ""}`);
    push("");
  }
  push("## Sources", "");
  view.evidenceList.forEach((e, i) => push(`${i + 1}. ${LABEL_TEXT[e.label]}: ${e.title}${e.publisher ? `, ${e.publisher}` : ""}, read ${e.retrieved}${e.url ? `. ${e.url}` : ""}`));
  push("", "## How to read this guide", "");
  push("**Levels** (from gates, computed in code):", "");
  for (const l of LEGEND.levels) push(`- Level ${l.level}, ${l.name}: ${l.meaning}`);
  push("", "**Evidence labels:**", "");
  for (const l of LEGEND.labels) push(`- ${l.label}: ${l.meaning}`);
  push("", "**Owner tags:**", "");
  for (const o of LEGEND.owners) push(`- ${o.owner}: ${o.meaning}`);
  push("", "Hands-on effort is our estimate from fixed times per step type. Calendar wait comes only from sources; where none exists the guide says so.", "");
  return L.join("\n");
}

