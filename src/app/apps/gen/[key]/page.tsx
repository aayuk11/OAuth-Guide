import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { GuideActions } from "@/components/client";
import { AppIcon, Callout, DocsShell, PageHeader } from "@/components/docs";
import { GUIDE_TOC, GuideBody } from "@/components/guide";
import { getGeneratedGuide } from "@/lib/agent/runs";
import { intakeQuery, parseIntake } from "@/lib/guide/intake";
import { buildView, summarizeGuide } from "@/lib/guide/view";
import { VERDICT_SHORT } from "@/lib/guide/verdict";
import { PROVIDERS } from "@/lib/llm/catalog";

const PROVIDER_VENDOR: Record<string, string> = Object.fromEntries(Object.values(PROVIDERS).map((p) => [p.id, p.vendor]));

export const dynamic = "force-dynamic";

export async function generateMetadata({ params }: PageProps<"/apps/gen/[key]">): Promise<Metadata> {
  const { key } = await params;
  const guide = await getGeneratedGuide(key).catch(() => null);
  if (!guide) return { title: "Guide not found" };
  const s = summarizeGuide(guide);
  const title = `${guide.app.name}: OAuth app setup (generated)`;
  const description = `${VERDICT_SHORT[s.verdict.type]}. Level ${s.minLevel}${s.maxLevel !== s.minLevel ? `–${s.maxLevel}` : ""}. ${guide.headline} Researched by agent ${guide.last_verified}.`;
  return { title, description, openGraph: { title, description }, robots: { index: false } };
}

export default async function GeneratedGuidePage({ params, searchParams }: PageProps<"/apps/gen/[key]">) {
  const { key } = await params;
  const sp = await searchParams;
  const guide = await getGeneratedGuide(key).catch(() => null);
  if (!guide) {
    return (
      <DocsShell active="/apps">
        <PageHeader
          crumbs={[{ href: "/apps", label: "Guides" }, { label: key }]}
          title={`No saved guide for “${key}”`}
          lead={`Generated guides are kept for 7 days${process.env.UPSTASH_REDIS_REST_URL || process.env.KV_REST_API_URL ? "" : ", and this deployment has no database, so they can also disappear when the server restarts"}.`}
        />
        <Link href={`/generate?q=${encodeURIComponent(key.replace(/-/g, " "))}`} className="inline-block rounded-md bg-fg px-3 py-2 text-sm font-medium text-bg no-underline">
          Research it again
        </Link>
      </DocsShell>
    );
  }
  if (!guide.paths.length) notFound();
  const intake = parseIntake(sp, guide);
  const view = buildView(guide, intake, typeof sp.path === "string" ? sp.path : null);
  const m = guide.meta;
  const r = m?.research;
  const cov = m?.coverage;
  const lowCoverage = !!cov && !m?.partial && cov.confirmed < Math.ceil(cov.total / 2);
  const model = m?.model ? `${m.provider && PROVIDER_VENDOR[m.provider] ? `${PROVIDER_VENDOR[m.provider]} ` : ""}${m.model}` : null;
  const q = intakeQuery(intake, { path: view.choice.explicit ? view.path.id : undefined });
  const plural = (n: number, w: string) => `${n} ${w}${n === 1 ? "" : w.endsWith("h") ? "es" : "s"}`;
  return (
    <DocsShell active="/apps" toc={GUIDE_TOC}>
      <PageHeader
        crumbs={[{ href: "/apps", label: "Guides" }, { label: guide.app.name }]}
        title={
          <span className="flex items-center gap-3">
            <AppIcon src={guide.app.logo} name={guide.app.name} size={36} />
            {guide.app.name}
          </span>
        }
        lead={guide.headline}
        meta={
          <>
            <span>Generated by agent</span>
            <span aria-hidden>·</span>
            <span>{guide.last_verified}</span>
            <span aria-hidden>·</span>
            <a href="#sources" className="link">
              {view.evidenceList.length} sources
            </a>
          </>
        }
      />
      <div className="mb-4">
        <GuideActions
          markdownUrl={`/api/guides/${key}/markdown?${q}`}
          appName={guide.app.name}
          recheckUrl={`/generate?q=${encodeURIComponent(m?.query ?? guide.app.name)}${guide.composio_slug ? `&toolkit=${guide.composio_slug}` : ""}&fresh=1`}
        />
      </div>
      <Callout tone={lowCoverage ? "warn" : "neutral"} title={lowCoverage ? "Needs review: many answers have no confirmed source" : "Written by the research agent, not reviewed by a person"}>
        {r?.web_search === false && (
          <>Researched without web search, because the API key&apos;s plan does not include it: only official pages the model named were read. A key with web search finds more. </>
        )}
        {cov && (
          <>
            {cov.confirmed} of {cov.total} core questions are answered with a source the agent could confirm
            {cov.answered > cov.confirmed ? `; ${cov.answered - cov.confirmed} more are answered from unconfirmed sources` : ""}
            {cov.answered < cov.total ? `; ${cov.total - cov.answered} are unknown` : ""}.{" "}
          </>
        )}
        {m?.critic && (
          <>
            {m.critic.checked - m.critic.downgraded} of {m.critic.checked} quotes were found on the pages cited
            {m.critic.downgraded ? `; ${m.critic.downgraded} downgraded` : ""}
            {m.critic.numbers_removed ? `; ${plural(m.critic.numbers_removed, "unsupported timeline")} removed` : ""}.{" "}
          </>
        )}
        {r && (
          <span className="text-fg-subtle">
            {plural(r.searches.length, "search")}, {plural(r.pages_read, "page")} read, {Math.round(r.duration_ms / 1000)} s{model ? `, ${model}` : ""}{r.model && r.model !== m?.model ? ` (research on ${r.model})` : ""}
            {r.cost_usd != null ? `, about $${r.cost_usd.toFixed(2)}` : ""}.{" "}
          </span>
        )}
        {m?.run_id && (
          <a href={`/api/runs/${m.run_id}`} className="link">
            Run log
          </a>
        )}
      </Callout>
      {m?.app_found === false && (
        <Callout tone="bad" title="App not identified">
          The agent could not confirm a real app matching “{m.query}”. Search again with the app&apos;s website.
        </Callout>
      )}
      {m?.partial && (
        <Callout tone="warn" title={`Partial guide: ${m.partial_reason}`}>
          Paths, gates and steps below are placeholders. Use Re-check to complete it.
          {m.research_notes && (
            <details className="mt-2">
              <summary className="cursor-pointer">Raw research notes</summary>
              <pre className="mt-2 max-h-80 overflow-auto whitespace-pre-wrap font-mono text-xs">{m.research_notes}</pre>
            </details>
          )}
        </Callout>
      )}
      <div className="mt-6">
        <GuideBody view={view} base={`/apps/gen/${key}`} storageKey={`steps:gen:${key}:${view.path.id}`} />
      </div>
    </DocsShell>
  );
}
